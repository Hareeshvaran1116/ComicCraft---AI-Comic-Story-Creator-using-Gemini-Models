logger = logging.getLogger(__name__)


def _sanitize_pdf_text(text: str) -> str:
    """Normalize text for standard PDF encoding."""
    if not text:
        return ""
    replacements = {
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2014": " - ",
        "\u2013": " - ",
        "\u2026": "...",
        "\u2022": "*",
        "\u00a0": " ",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    # Ensure ASCII-safe fallback if needed
    return text.encode("latin-1", "replace").decode("latin-1")


class ComicPDF(FPDF):
    def __init__(self, story_title: str = "ComicCraft AI Comic"):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.story_title = story_title
        self.set_auto_page_break(auto=True, margin=15)

    def header(self):
        if self.page_no() == 1:
            return  # Cover page has its own layout
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(100, 116, 139)
        self.cell(0, 8, _sanitize_pdf_text(self.story_title), align="L")
        self.set_font("Helvetica", "I", 9)
        self.cell(0, 8, "ComicCraft AI Studio", align="R", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(226, 232, 240)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 8, f"Page {self.page_no()} | Generated by ComicCraft AI", align="C")


def save_pdf(
    comic_id: str,
    panels: List[ComicPanel],
    story_title: str = "ComicCraft AI Comic",
    character_name: str = "",
    setting_name: str = "",
    tone: str = "",
    art_style: str = "",
) -> str:
    """Compile comic panels and stories into a multi-page PDF document."""
    pdf_out = export_path(comic_id)
    pdf_out.parent.mkdir(parents=True, exist_ok=True)

    pdf = ComicPDF(story_title=story_title)

    # ---------------- PAGE 1: COVER / TITLE PAGE ----------------
    pdf.add_page()

    # Cover Banner
    pdf.ln(15)
    pdf.set_fill_color(30, 41, 59)  # Slate dark
    pdf.rect(10, 25, 190, 70, style="F")

    pdf.set_y(35)
    pdf.set_font("Helvetica", "B", 26)
    pdf.set_text_color(248, 250, 252)
    pdf.multi_cell(190, 12, _sanitize_pdf_text(story_title), align="C")

    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(56, 189, 248)  # Cyan accent
    pdf.cell(0, 8, "AI GENERATED COMIC BOOK", align="C", new_x="LMARGIN", new_y="NEXT")

    # Comic Metadata Card
    pdf.set_y(105)
    pdf.set_fill_color(241, 245, 249)
    pdf.set_draw_color(203, 213, 225)
    pdf.rect(15, 105, 180, 50, style="DF")

    pdf.set_xy(20, 110)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(51, 65, 85)

    if character_name:
        pdf.cell(85, 8, f"Hero / Protagonist: {_sanitize_pdf_text(character_name)}")
    if setting_name:
        pdf.cell(85, 8, f"Setting: {_sanitize_pdf_text(setting_name)}", new_x="LMARGIN", new_y="NEXT")
        pdf.set_x(20)

    if tone:
        pdf.cell(85, 8, f"Tone: {_sanitize_pdf_text(tone.capitalize())}")
    if art_style:
        pdf.cell(85, 8, f"Art Style: {_sanitize_pdf_text(art_style.capitalize())}", new_x="LMARGIN", new_y="NEXT")
        pdf.set_x(20)

    pdf.cell(85, 8, f"Total Panels: {len(panels)}")
    pdf.cell(85, 8, f"Comic ID: {comic_id}", new_x="LMARGIN", new_y="NEXT")

    # Cover Panel Teaser if panel 1 image exists
    img_1_path = panel_image_path(comic_id, 1)
    if img_1_path.exists():
        pdf.set_y(165)
        pdf.image(str(img_1_path), x=35, y=165, w=140)

    # ---------------- CONSECUTIVE PANEL PAGES ----------------
    for panel in panels:
        pdf.add_page()

        # Panel Header Badge
        pdf.set_fill_color(15, 23, 42)
        pdf.rect(10, 18, 190, 12, style="F")
        pdf.set_xy(14, 20)
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(255, 255, 255)
        pdf.cell(0, 8, _sanitize_pdf_text(panel.title))

        # Panel Image
        img_path = panel_image_path(comic_id, panel.panel_number)
        current_y = 35
        if img_path.exists():
            pdf.image(str(img_path), x=15, y=current_y, w=180)
            current_y += 125
        else:
            current_y += 10

        # Scene Description (in italics)
        if panel.scene_description:
            pdf.set_xy(15, current_y)
            pdf.set_font("Helvetica", "I", 10)
            pdf.set_text_color(71, 85, 105)
            pdf.multi_cell(180, 5, _sanitize_pdf_text(panel.scene_description))
            current_y = pdf.get_y() + 4

        # Narration Box
        if panel.narration:
            pdf.set_xy(15, current_y)
            pdf.set_fill_color(254, 243, 199)  # Warm amber comic caption
            pdf.set_draw_color(245, 158, 11)
            text_narr = _sanitize_pdf_text(panel.narration)
            narr_height = max(12, int(len(text_narr) / 80) * 6 + 8)
            pdf.rect(15, current_y, 180, narr_height, style="DF")
            pdf.set_xy(18, current_y + 2)
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(120, 53, 15)
            pdf.multi_cell(174, 5, text_narr)
            current_y = current_y + narr_height + 4

        # Dialogue Bubble Box
        if panel.dialogue:
            pdf.set_xy(15, current_y)
            pdf.set_fill_color(240, 253, 250)  # Light cyan speech box
            pdf.set_draw_color(13, 148, 136)
            text_dlg = _sanitize_pdf_text(panel.dialogue)
            dlg_height = max(12, int(len(text_dlg) / 80) * 6 + 8)
            pdf.rect(15, current_y, 180, dlg_height, style="DF")
            pdf.set_xy(18, current_y + 2)
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(17, 94, 89)
            pdf.multi_cell(174, 5, text_dlg)

    try:
        pdf.output(str(pdf_out))
        logger.info("Comic PDF exported successfully to %s", pdf_out)
    except Exception as exc:
        logger.error("Failed to generate PDF: %s", exc)
        raise

    return f"/download/{comic_id}"

