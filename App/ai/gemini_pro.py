import os
from typing import Any

try:
    from google import genai
except ImportError:
    genai = None


def _get_prompt_text(request_data: Any) -> str:
    """Convert the request object into useful text."""

    if isinstance(request_data, str):
        return request_data.strip()

    if isinstance(request_data, dict):
        story_prompt = request_data.get("story_prompt", "")
        character_name = request_data.get("character_name", "")
        setting = request_data.get("setting", "")

        return (
            f"Story prompt: {story_prompt}\n"
            f"Character: {character_name}\n"
            f"Setting: {setting}"
        ).strip()

    story_prompt = getattr(request_data, "story_prompt", "")
    character_name = getattr(request_data, "character_name", "")
    setting = getattr(request_data, "setting", "")

    return (
        f"Story prompt: {story_prompt}\n"
        f"Character: {character_name}\n"
        f"Setting: {setting}"
    ).strip()


def generate_story(request_data: Any, outline: str = "") -> str:
    """
    Generate the full comic story.

    Accepts the request data plus the outline generated by the
    outline stage.
    """

    prompt_text = _get_prompt_text(request_data)

    if not outline:
        outline = "Create a beginning, middle, and ending."

    api_key = os.getenv("GEMINI_API_KEY")

    if genai is None or not api_key:
        return _fallback_story(prompt_text, outline)

    try:
        client = genai.Client(api_key=api_key)

        response = client.models.generate_content(
            model="gemini-2.5-pro",
            contents=(
                "Create a complete comic story using the information below.\n\n"
                f"{prompt_text}\n\n"
                f"Comic outline:\n{outline}\n\n"
                "Write the story as clear scenes suitable for a comic."
            ),
        )

        text = getattr(response, "text", None)

        if text:
            return text

    except Exception as exc:
        print(f"Gemini Pro error: {exc}")

    return _fallback_story(prompt_text, outline)


def _fallback_story(prompt_text: str, outline: str) -> str:
    """Local fallback so the application works without Gemini."""

    return (
        f"{prompt_text}\n\n"
        "SCENE 1 — THE BEGINNING\n"
        "Our hero discovers that something unusual is happening.\n\n"
        "SCENE 2 — THE CHALLENGE\n"
        "The hero encounters an unexpected problem and decides to act.\n\n"
        "SCENE 3 — THE ADVENTURE\n"
        "The hero follows the clues and faces the main challenge.\n\n"
        "SCENE 4 — THE RESOLUTION\n"
        "The hero overcomes the challenge and discovers something important.\n\n"
        f"STORY OUTLINE USED:\n{outline}"
    )


__all__ = ["generate_story"]